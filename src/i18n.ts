const locale = ref<Locale>(detectLocale())

function detectLocale(): Locale {
  if (typeof window !== 'undefined') {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY)
      if (stored === 'en' || stored === 'zh') return stored
    }
    catch { /* storage can be unavailable in privacy mode */ }
  }
  const candidates = typeof navigator !== 'undefined'
    ? [...(navigator.languages ?? []), navigator.language]
    : []
  return candidates.some(value => /^zh(?:-|$)/i.test(value)) ? 'zh' : 'en'
}

function applyDocumentLocale(value: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en'
}

applyDocumentLocale(locale.value)

export function translate(key: string, params: Record<string, string | number> = {}): string {
  const source = messages[locale.value][key] ?? messages.en[key] ?? key
  return Object.entries(params).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), source)
}

export function setLocale(value: Locale) {
  locale.value = value
  applyDocumentLocale(value)
  if (typeof window !== 'undefined') {
    try { window.localStorage.setItem(STORAGE_KEY, value) }
    catch { /* storage can be unavailable in privacy mode */ }
  }
}

export function useI18n() {
  return {
    locale,
    isEnglish: computed(() => locale.value === 'en'),
    t: translate,
    setLocale,
    languageOptions: [
      { value: 'en' as const, label: translateFor('en', 'language.en') },
      { value: 'zh' as const, label: translateFor('en', 'language.zh') },
    ],
  }
}

function translateFor(target: Locale, key: string): string {
  return messages[target][key] ?? key
}

