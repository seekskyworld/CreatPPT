export function localizeQualityIssue(issue: QualityIssue): string {
  const params: Record<string, string | number> = {}
  const match = issue.message.match(/（(\d+)\/(\d+)）|\((\d+)\/(\d+)\)/)
  if (match) {
    params.value = Number(match[1] ?? match[3])
    params.limit = Number(match[2] ?? match[4])
  }
  const fieldMatch = issue.message.match(/^([^ ]+) 内容偏长/)
  if (fieldMatch) params.field = fieldMatch[1]
  const assetMatch = issue.message.match(/素材 ([^ ]+)/)
  if (assetMatch) params.asset = assetMatch[1].replace(/[。]$/, '')
  const layoutMatch = issue.message.match(/^([^ ]+) 页面缺少图片/)
  if (layoutMatch) params.layout = layoutLabel(layoutIdFromName(layoutMatch[1]))
  const key = `quality.${issue.code}`
  if (!messages[locale.value][key] && !messages.en[key]) return issue.message
  return translate(key, params)
}

function layoutIdFromName(value: string): SlideLayout {
  if (['cover', 'agenda', 'statement', 'metrics', 'split', 'comparison', 'chart', 'timeline', 'gallery', 'quote', 'closing'].includes(value)) return value as SlideLayout
  const found = (Object.keys(messages.zh) as string[]).find(key => key.startsWith('layout.') && messages.zh[key] === value)
  return (found?.slice('layout.'.length) as SlideLayout | undefined) ?? 'statement'
}
